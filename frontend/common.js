(function buildWebsiteLayout() {
    const page = document.body.dataset.page;
    const navbar = document.querySelector('.ehr-navbar .nav-container');
    const main = document.querySelector('main.ehr-workspace');
    if (!navbar || !main) return;
    document.body.classList.add('nx-site');

    const L = () => NX_LAYOUT[window.neutrixLang] || NX_LAYOUT.English;
    const inIssue = !!window.neutrixActiveIssue;

    // Scroll progress bar + back-to-top pill, like the website
    const progress = document.createElement('div');
    progress.className = 'nx-scroll-progress';
    document.body.prepend(progress);
    const topBtn = document.createElement('button');
    topBtn.type = 'button';
    topBtn.className = 'nx-top-btn';
    topBtn.addEventListener('click', () => window.scrollTo({ top: 0, behavior: 'smooth' }));
    document.body.appendChild(topBtn);
    window.addEventListener('scroll', () => {
        const max = document.documentElement.scrollHeight - window.innerHeight;
        progress.style.width = max > 0 ? `${(window.scrollY / max) * 100}%` : '0%';
        topBtn.classList.toggle('visible', window.scrollY > 400);
    }, { passive: true });

    // Pill menu in the top bar
    const pills = document.createElement('nav');
    pills.className = 'nx-nav-links';
    navbar.querySelector('.hospital-brand').insertAdjacentElement('afterend', pills);

    function navItems() {
        if (!inIssue) return [['issues', 'issues.html'], ['website', 'home.html']];
        const hasReport = !!storeGet('neutrixReport');
        const hasProgress = loadFollowups().some(f => f.comparison);
        const items = [['dashboard', 'index.html'], ['upload', 'summary.html']];
        if (hasReport) items.push(['report', 'report.html'], ['medplan', 'medplan.html'], ['checkups', 'checkups.html']);
        if (hasProgress) items.push(['improvements', 'improvements.html']);
        const ex = window.exerciseInfo && exerciseInfo();
        if (ex && ex.exercises.length) items.push(['exercise', 'exercise.html']);
        items.push(['tracking', 'tracking.html'], ['briefing', 'briefing.html']);
        return items;
    }

    function renderNav() {
        const labels = L().nav;
        pills.innerHTML = '';
        const current = page === 'dashboard' ? 'dashboard' : page;
        navItems().forEach(([key, href]) => {
            const a = document.createElement('a');
            a.href = href;
            a.className = 'nx-nav-item' + ((key === current || (key === 'medplan' && page === 'schedule')) ? ' active' : '');
            a.textContent = labels[key];
            pills.appendChild(a);
        });
    }

    // Centred hero heading above the page
    const hero = document.createElement('section');
    hero.className = 'nx-hero';
    main.insertAdjacentElement('beforebegin', hero);
    const dashHero = document.querySelector('.dash-hero');
    if (dashHero) {
        hero.appendChild(dashHero);          // the dashboard brings its own welcome heading
    } else {
        hero.innerHTML = `<span class="nx-eyebrow">NEUTRIX HEALTH • <span class="nx-eyebrow-live"></span></span>
                          <h1 class="nx-hero-title"></h1><p class="nx-hero-sub"></p>`;
        document.body.classList.add('nx-has-hero');
    }

    function renderHero() {
        const texts = L().hero[page];
        if (!texts || dashHero) return;
        hero.querySelector('.nx-eyebrow-live').textContent = texts[0];
        hero.querySelector('.nx-hero-title').textContent = texts[1];
        hero.querySelector('.nx-hero-sub').textContent = texts[2];
    }

    // Website footer
    const footer = document.createElement('footer');
    footer.className = 'px-footer nx-footer';
    document.body.appendChild(footer);

    function renderFooter() {
        const f = L().footer;
        const n = L().nav;
        const link = (href, text) => `<a href="${href}">${text}</a>`;
        const toolLinks = inIssue
            ? [link('index.html', n.dashboard), link('summary.html', n.upload), link('report.html', n.report),
               link('medplan.html', n.medplan), link('checkups.html', n.checkups)].concat(((window.exerciseInfo && exerciseInfo()) || { exercises: [] }).exercises.length ? [link('exercise.html', n.exercise)] : [], [link('tracking.html', n.tracking), link('briefing.html', n.briefing)]).join('')
            : link('issues.html', n.issues);
        footer.innerHTML = `
            <div class="footer-container">
                <div class="footer-grid">
                    <div class="footer-col brand-col">
                        <div class="nx-footer-logo">${NEUTRIX_LOGO}</div>
                        <p class="copyright">Neutrix Health © 2026</p>
                    </div>
                    <div class="footer-col"><span class="col-title">${f.app}</span>${link('issues.html', n.issues)}${inIssue ? link('index.html', n.dashboard) : ''}</div>
                    <div class="footer-col"><span class="col-title">${f.tools}</span>${toolLinks}</div>
                    <div class="footer-col"><span class="col-title">${f.help}</span>${link('home.html', f.website)}${link('home.html#safety', f.safety)}</div>
                    <div class="footer-col nx-footer-note"><p>${f.note}</p></div>
                </div>
                <div class="footer-watermark">NEUTRIX HEALTH</div>
            </div>`;
        topBtn.textContent = f.top;
    }

    function renderLayout() {
        renderNav();
        renderHero();
        renderFooter();
    }
    renderLayout();
    document.addEventListener('neutrix:langchange', renderLayout);
    document.addEventListener('neutrix:exercises', () => { renderNav(); renderFooter(); });   // Exercise link appears once found
})();

