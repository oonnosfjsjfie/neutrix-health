// Small, safe Markdown for pages without the Markdown library (headings, bold, lists, links, rules).
// Everything is escaped first, so no HTML from the text can run.
function miniMarkdown(text) {
    const esc = s => s.replace(/&/g, '&amp;').replace(/</g, '&lt;').replace(/>/g, '&gt;').replace(/"/g, '&quot;');
    const inline = s => esc(s)
        .replace(/`([^`]+)`/g, '<code>$1</code>')
        .replace(/\*\*([^*]+)\*\*/g, '<strong>$1</strong>')
        .replace(/(^|[^*])\*([^*\s][^*]*)\*/g, '$1<em>$2</em>')
        .replace(/\[([^\]]+)\]\((https?:\/\/[^\s)]+)\)/g, '<a href="$2" target="_blank" rel="noopener noreferrer">$1</a>');
    const out = [];
    let list = null;        // 'ul' or 'ol'
    let para = [];
    const flushPara = () => { if (para.length) { out.push('<p>' + para.map(inline).join('<br>') + '</p>'); para = []; } };
    const closeList = () => { if (list) { out.push(`</${list}>`); list = null; } };
    String(text).replace(/\r/g, '').split('\n').forEach(raw => {
        const line = raw.trimEnd();
        let m;
        if (!line.trim()) { flushPara(); closeList(); return; }
        if ((m = line.match(/^\s{0,3}(#{1,6})\s+(.*)$/))) {
            flushPara(); closeList();
            const level = Math.min(6, m[1].length + 1);   // keep headings small inside cards and the chat
            out.push(`<h${level}>${inline(m[2])}</h${level}>`);
            return;
        }
        if (/^\s{0,3}([-*_])(\s*\1){2,}\s*$/.test(line)) { flushPara(); closeList(); out.push('<hr>'); return; }
        if ((m = line.match(/^\s*[-*•]\s+(.*)$/))) {
            flushPara();
            if (list !== 'ul') { closeList(); out.push('<ul>'); list = 'ul'; }
            out.push(`<li>${inline(m[1])}</li>`);
            return;
        }
        if ((m = line.match(/^\s*\d+[.)]\s+(.*)$/))) {
            flushPara();
            if (list !== 'ol') { closeList(); out.push('<ol>'); list = 'ol'; }
            out.push(`<li>${inline(m[1])}</li>`);
            return;
        }
        closeList();
        para.push(line);
    });
    flushPara(); closeList();
    return out.join('');
}
window.miniMarkdown = miniMarkdown;

// ---------- AI translation of generated content ----------
window.translateText = async function (text, lang) {
    const controller = new AbortController();
    const timer = setTimeout(() => controller.abort(), 90000);
    try {
        const res = await fetch(`${API_BASE}/api/translate`, {
            method: 'POST',
            headers: { 'Content-Type': 'application/json' },
            body: JSON.stringify({ text: text, target_language: lang }),
            signal: controller.signal
        });
        if (!res.ok) throw new Error(`Server error ${res.status}`);
        const data = await res.json();
        if (data.ok === false) throw new Error(data.text);
        return data.text;
    } finally {
        clearTimeout(timer);
    }
};

// map looks like { English: "...", Malayalam: "..." }. Fills in the missing language.
window.getLocalized = async function (map, lang) {
    if (map[lang]) return map[lang];
    const source = map.English || map.Malayalam || Object.values(map)[0];
    if (!source) return '';
    map[lang] = await translateText(source, lang);
    return map[lang];
};

// ---------- Apply UI text ----------
window.applyTexts = function (root = document) {
    const dict = I18N[window.neutrixLang];
    root.querySelectorAll('[data-i18n]').forEach(el => {
        const value = dict[el.dataset.i18n];
        if (value !== undefined) el.textContent = value;
    });
    root.querySelectorAll('[data-i18n-html]').forEach(el => {
        const value = dict[el.dataset.i18nHtml];
        if (value !== undefined) el.innerHTML = value;
    });
    root.querySelectorAll('[data-i18n-placeholder]').forEach(el => {
        el.placeholder = dict[el.dataset.i18nPlaceholder];
    });
    root.querySelectorAll('[data-i18n-title]').forEach(el => {
        el.title = dict[el.dataset.i18nTitle];
    });
};

// Show navbar links only where there is something to open
window.updateNav = function () {
    const current = document.body.dataset.page;
    const hasReport = !!storeGet('neutrixReport');
    const hasSchedule = !!storeGet('neutrixSchedule');
    document.querySelectorAll('[data-nav]').forEach(link => {
        const target = link.dataset.nav;
        let show = target !== current;
        if (target === 'report' && !hasReport) show = false;
        if (target === 'schedule' && !hasSchedule) show = false;
        link.classList.toggle('hidden', !show);
    });
};

