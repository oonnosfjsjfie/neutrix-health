// Where the AI backend is:
// - opened with "python -m http.server 5500" (or from a file) -> the backend on this computer
// - opened from the backend itself (one-link / live server mode) -> the same address as the page
window.API_BASE = (location.protocol === 'file:' || ['5500', '5501'].includes(location.port))
    ? 'http://127.0.0.1:8000'
    : '';
window.neutrixLang = 'English';

// Translated UI text, e.g. t('serverError', { msg: 'x' })
window.t = function (key, vars = {}) {
    const dict = I18N[window.neutrixLang] || I18N.English;
    let text = dict[key] ?? I18N.English[key] ?? key;
    for (const name in vars) text = text.replace(`{${name}}`, vars[name]);
    return text;
};

// ---------- Storage ----------
window.storeGet = function (key) {
    try { return JSON.parse(localStorage.getItem(key) || 'null'); } catch (e) { return null; }
};
window.storeSet = function (key, value) {
    try { localStorage.setItem(key, JSON.stringify(value)); return true; } catch (e) { return false; }
};

// Saved report, upgraded to the per-language format if needed
window.loadReport = function () {
    const r = storeGet('neutrixReport');
    if (!r) return null;
    if (!r.summaries) {
        r.summaries = {};
        if (r.summary) r.summaries[r.language || 'English'] = r.summary;
    }
    return r;
};

// New reports added later for the same issue
window.loadFollowups = function () {
    return storeGet('neutrixFollowups') || [];
};

// All report text for this issue: the first upload plus every later report
window.fullReportText = function (r) {
    if (!r) return '';
    let text = r.reportText || '';
    loadFollowups().forEach(f => {
        const date = (f.createdAt || '').slice(0, 10);
        text += `\n\n===== LATER REPORT (added ${date}) =====\n${f.text || ''}`;
    });
    return text;
};

// Changes whenever files are added to this issue (used to remake AI pages automatically).
// legacy=true gives the version an older saved item is assumed to have.
window.reportVersion = function (r, legacy) {
    if (!r) return '';
    const followups = loadFollowups().length;
    if (legacy) return `${r.createdAt}|0`;
    return `${r.updatedAt || r.createdAt}|${followups}`;
};

// ---------- Exercises written in the reports (camera exercise coach) ----------
// Saved as { version, exercises, restrictions_en, restrictions_ml, checkedAt }.
// Only valid while the reports have not changed (same reportVersion).
window.exerciseInfo = function () {
    const r = loadReport();
    const saved = storeGet('neutrixExercises');
    return r && saved && saved.version === reportVersion(r) ? saved : null;
};
let exerciseRequest = null;
window.fetchExercises = function () {
    const r = loadReport();
    if (!r) return Promise.resolve(null);
    if (exerciseRequest) return exerciseRequest;
    const version = reportVersion(r);
    exerciseRequest = fetch(`${API_BASE}/api/exercises`, {
        method: 'POST',
        headers: { 'Content-Type': 'application/json' },
        body: JSON.stringify({ report_text: fullReportText(r) })
    })
        .then(res => res.json())
        .then(data => {
            if (!data || !data.ok) throw new Error((data && data.message) || 'No answer from the AI');
            const info = {
                version,
                exercises: data.exercises || [],
                restrictions_en: data.restrictions_en || [],
                restrictions_ml: data.restrictions_ml || [],
                checkedAt: new Date().toISOString()
            };
            storeSet('neutrixExercises', info);
            return info;
        })
        .finally(() => { exerciseRequest = null; });
    return exerciseRequest;
};

// ---------- Summary versions (history on the Reports Portal) ----------
// Each entry: { kind: 'first' | 'update' | 'refresh', createdAt, files, summary: { English, Malayalam } }
window.summaryHistory = function (r) {
    if (!r) return [];
    if (!Array.isArray(r.summaryHistory)) {
        // Older records: rebuild what we can
        const names = (list, key) => Array.isArray(list) ? list.map(f => f.name).join(', ') : (r[key] || '');
        const updates = r.updates || [];
        r.summaryHistory = [{
            kind: 'first',
            createdAt: r.createdAt,
            files: [names(r.firstFiles || r.files, 'dischargeName'), names(r.firstBills || r.bills, 'billName')].filter(Boolean).join(', '),
            summary: r.firstSummary || (updates.length ? null : { ...(r.summaries || {}) })
        }].concat(updates.map(u => ({
            kind: 'update',
            createdAt: u.createdAt,
            files: [names(u.files), names(u.bills)].filter(Boolean).join(', '),
            summary: u.summary
        })));
    }
    return r.summaryHistory;
};

window.addSummaryVersion = function (r, kind, files, summaryMap) {
    summaryHistory(r).push({ kind, createdAt: new Date().toISOString(), files, summary: { ...summaryMap } });
};

// ---------- Medicine schedule versions ----------
// A schedule keeps a list of versions: { from: 'YYYY-MM-DD', doses: [...] }.
// When a new report changes the medicines, a new version starts that day,
// so earlier days still show the medicines that were taken then.
window.scheduleVersions = function (s) {
    if (!s) return [];
    if (!Array.isArray(s.versions)) {
        s.versions = [{ from: s.startDate, doses: s.doses || [] }];   // older saved schedules
    }
    return s.versions;
};

window.dayKeyShift = function (key, days) {
    const [y, m, d] = key.split('-').map(Number);
    const date = new Date(y, m - 1, d);
    date.setDate(date.getDate() + days);
    return dayKey(date);
};

// Last day a medicine is taken, from its written duration ("5 days", "1 year", "till 15-10-2027").
// Returns null when it continues (or the duration isn't clear).
window.doseEndDay = function (dose, fromKey) {
    const text = (dose.duration || '').toLowerCase();
    const date = text.match(/(\d{1,2})[-\/.](\d{1,2})[-\/.](\d{4})/);
    if (date) return `${date[3]}-${date[2].padStart(2, '0')}-${date[1].padStart(2, '0')}`;
    const n = text.match(/(\d+)\s*(day|week|month|year)/);
    if (!n) return null;
    const count = Number(n[1]);
    const days = { day: 1, week: 7, month: 30, year: 365 }[n[2]] * count;
    return dayKeyShift(fromKey, days - 1);
};

// The doses to take on a given day
window.dosesForDay = function (s, key) {
    const versions = scheduleVersions(s);
    let version = versions[0];
    versions.forEach(v => { if (v.from <= key) version = v; });
    if (!version) return [];
    return version.doses.filter(d => {
        const end = doseEndDay(d, version.from);
        return !end || key <= end;
    });
};

